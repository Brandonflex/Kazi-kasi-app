"""The DATABASE_URL dispatcher.

``db.connect()`` now opens either sqlite or psycopg depending on the argument.
Three invariants, each cheap to pin:

* an explicit path always wins over DATABASE_URL in the environment — otherwise
  a test that sets DATABASE_URL=postgres://example and then opens an in-memory
  sqlite connection would crash;
* a ``url=`` kwarg that looks like postgres goes through psycopg;
* no argument at all reads DATABASE_URL from the environment.
"""

from __future__ import annotations

import os

import pytest

from kazikasi import db


class TestExplicitPathWins:
    """Tests set DATABASE_URL=postgres://example and expect the sqlite path."""

    def test_memory_connection_ignores_database_url(self, monkeypatch):
        monkeypatch.setenv("DATABASE_URL", "postgres://example.invalid")
        conn = db.connect(":memory:")
        try:
            counts = db.table_counts(conn)
        finally:
            conn.close()
        # 14 tables is the current schema; the number matters less than the
        # fact that we got *a* schema back instead of a connection error.
        assert counts["jobs"] == 0

    def test_a_real_file_path_also_ignores_database_url(self, monkeypatch, tmp_path):
        monkeypatch.setenv("DATABASE_URL", "postgres://example.invalid")
        path = tmp_path / "x.sqlite"
        conn = db.connect(path)
        try:
            assert db.table_counts(conn)["jobs"] == 0
        finally:
            conn.close()
        assert path.exists()


class TestTheUrlKwarg:
    def test_postgres_url_selects_psycopg(self, monkeypatch):
        # We cannot actually connect — but the dispatcher must at least reach
        # for psycopg before it fails, and the failure message must name the
        # host we asked for, not "could not find sqlite file".
        monkeypatch.delenv("DATABASE_URL", raising=False)
        with pytest.raises(Exception) as exc:
            db.connect(url="postgres://no-such-host.invalid/kazikasi")
        # psycopg reports "could not translate host name" or "failed to resolve"
        # — both contain the hostname we asked for.
        assert "no-such-host.invalid" in str(exc.value)

    def test_no_args_reads_database_url(self, monkeypatch):
        monkeypatch.setenv("DATABASE_URL", "postgres://no-such-host.invalid/kazikasi")
        with pytest.raises(Exception) as exc:
            db.connect()
        assert "no-such-host.invalid" in str(exc.value)


class TestThePostgresSchemaTranslates:
    """The SQLite schema uses AUTOINCREMENT; Postgres does not have that keyword.
    The translator must produce something psycopg can parse."""

    def test_no_autoincrement_in_postgres_schema(self):
        assert "AUTOINCREMENT" not in db.POSTGRES_SCHEMA

    def test_identity_replaces_autoincrement(self):
        # Every table that had AUTOINCREMENT now has GENERATED BY DEFAULT AS IDENTITY
        # — the form that accepts both explicit inserts and auto-generation.
        assert "GENERATED BY DEFAULT AS IDENTITY" in db.POSTGRES_SCHEMA

    def test_table_count_matches_sqlite(self):
        sqlite_tables = db.SCHEMA.count("CREATE TABLE")
        pg_tables = db.POSTGRES_SCHEMA.count("CREATE TABLE")
        assert pg_tables == sqlite_tables, (
            f"Postgres schema has {pg_tables} tables but SQLite has {sqlite_tables}"
        )
